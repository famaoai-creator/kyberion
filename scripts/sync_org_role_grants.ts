import { format as prettierFormat, resolveConfig as resolvePrettierConfig } from 'prettier';
import { pathResolver } from '@agent/core/path-resolver';
import { safeExistsSync, safeReadFile } from '@agent/core/secure-io';
import { parseSafeJsonObjectInput } from '@agent/core/foundation';
import {
  loadAuthorityRoleCards,
  loadOrgRoleCards,
  ORG_ROLE_CLASSES,
  projectRoleAuthorityMap,
  validateOrgRoleCards,
  type RoleAuthorityMapGroups,
} from '@agent/core/organization/authority-role-registry';
import { defineGenerator, isDirectScript, type GeneratedFile } from './lib/harness.js';

/**
 * Concept model v2 D6: an Org Role carries no permissions of its own; its card
 * (`knowledge/product/roles/<role>/role.json`) declares the default Grant it
 * maps to as pointers into the one role registry (`default_grant`:
 * `authority_role`, `base_role`, `execution_mode`). This generator projects
 * the cards into `knowledge/product/governance/role-authority-map.json` and
 * `--check` is its drift gate. Every `authority_role` must be an Authority Role
 * card and every `base_role` a known base role, else the run fails.
 */
const MAP = pathResolver.knowledge('product/governance/role-authority-map.json');

export const ROLE_AUTHORITY_MAP_DESCRIPTION =
  'Generated by `pnpm kyberion sync org-role-grants` from the Org Role cards (knowledge/product/roles/<role>/role.json default_grant); edit the card, not this file. Maps each Org Role to its execution mode, base role (persona) and authority_role. system_roles maintain Kyberion itself; mission_roles execute user work; context_roles are knowledge-only (no runtime authority).';

function existingOrder(): Partial<Record<keyof RoleAuthorityMapGroups, string[]>> {
  if (!safeExistsSync(MAP)) return {};
  const current = parseSafeJsonObjectInput(
    String(safeReadFile(MAP, { encoding: 'utf8' })),
    'role-authority-map.json'
  );
  const order: Partial<Record<keyof RoleAuthorityMapGroups, string[]>> = {};
  for (const roleClass of ORG_ROLE_CLASSES) {
    const group = `${roleClass}_roles` as const;
    const entries = current[group];
    if (!Array.isArray(entries)) continue;
    order[group] = entries
      .map((entry: unknown) =>
        entry && typeof entry === 'object' ? (entry as { role?: unknown }).role : undefined
      )
      .filter((role): role is string => typeof role === 'string');
  }
  return order;
}

async function render(): Promise<GeneratedFile[]> {
  const cards = loadOrgRoleCards();
  if (Object.keys(cards).length === 0) {
    throw new Error(
      '[ORG_ROLE_CARDS_MISSING] knowledge/product/roles/*/role.json is missing | restore the Org Role cards; they are the source of role-authority-map.json'
    );
  }
  const errors = validateOrgRoleCards(cards, loadAuthorityRoleCards() ?? {});
  if (errors.length > 0) {
    throw new Error(
      `[ORG_ROLE_GRANT_INVALID] ${errors.length} default_grant pointer(s) do not resolve in the role registry — ${errors.join('; ')} | fix default_grant in knowledge/product/roles/<role>/role.json`
    );
  }
  const prettierConfig = (await resolvePrettierConfig(MAP)) ?? {};
  const content = await prettierFormat(
    JSON.stringify(
      {
        $schema: '../schemas/role-authority-map.schema.json',
        version: '1.0.0',
        description: ROLE_AUTHORITY_MAP_DESCRIPTION,
        ...projectRoleAuthorityMap(cards, existingOrder()),
      },
      null,
      2
    ),
    { ...prettierConfig, parser: 'json' }
  );
  return [{ path: MAP, content }];
}

export const runSyncOrgRoleGrants = defineGenerator({
  id: 'org-role-grants',
  outputs: (_context, files) => files.map((file) => file.path),
  normalize: (content) =>
    JSON.stringify(parseSafeJsonObjectInput(content, 'role-authority-map generated output')),
  render,
});

if (
  isDirectScript(import.meta.url, 'sync_org_role_grants.ts') ||
  isDirectScript(import.meta.url, 'sync_org_role_grants.js')
)
  void runSyncOrgRoleGrants();
