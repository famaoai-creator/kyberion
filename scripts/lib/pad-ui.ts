export function escapePadHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** JSON safe inside `<script type="application/json">` (no `</script`, `<!--`, or line separators). */
export function toPadInlineJson(value: unknown): string {
  return JSON.stringify(value ?? null)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

/** Inline script source that cannot close its element early. */
function inlineScriptSource(source: string): string {
  return source.replace(/<\/(script)/gi, '<\\/$1').replace(/<\!--/g, '<\\!--');
}

/**
 * Pre-paint theme: the shared stored choice (`kyberion.ui.theme`) as
 * `data-theme`; otherwise no attribute, so the generated tokens follow
 * `prefers-color-scheme`. Storage can be unavailable — never throw.
 */
export const PAD_THEME_PREPAINT_SCRIPT = `(function(){var r=document.documentElement,v=null;try{v=window.localStorage.getItem(${JSON.stringify(PAD_THEME_STORAGE_KEY)});}catch(e){}if(v==='light'||v==='dark')r.setAttribute('data-theme',v);else r.removeAttribute('data-theme');})();`;

export interface PadHeaderOptions {
  locale: SupportedLocale;
  /** Plain text (escaped here). */
  title: string;
  /** Plain text (escaped here). */
  subtitle?: string;
  /** Trusted markup placed before the display controls. */
  actionsHtml?: string;
}

/**
 * The common pad header: title + "Local pad" badge, optional subtitle, and
 * an actions slot ending in the `[data-pad-display-controls]` host that
 * `pad-client.js` fills with `ui:display-controls`.
 */
export function renderPadHeader(options: PadHeaderOptions): string {
  const t = padT(options.locale);
  const subtitle = options.subtitle
    ? `<p class="kb-page-header__subtitle">${escapePadHtml(options.subtitle)}</p>`
    : '';
  return [
    '<header class="kb-page-header">',
    '<div class="kb-page-header__titles">',
    `<h1 class="kb-page-header__title">${escapePadHtml(options.title)} <span class="kb-badge" data-role="local-pad">${escapePadHtml(t('local_pads:badge'))}</span></h1>`,
    subtitle,
    '</div>',
    '<div class="kb-page-header__actions">',
    options.actionsHtml ?? '',
    '<div data-pad-display-controls></div>',
    '</div>',
    '</header>',
  ].join('');
}

export interface PadPageOptions {
  locale: SupportedLocale;
  /** Plain-text page title (escaped); the document title becomes "{title} — Kyberion". */
  title: string;
  /** Trusted pad markup, placed inside `<main class="kb-app-shell__main">`. */
  bodyHtml: string;
  /** Trusted extra `<head>` markup (page CSS, preloads). */
  headExtra?: string;
  /** Inline ES module source (import from `/pad-ui/pad-client.js`, `/shared-ui/*.js`). */
  scriptModule?: string;
  /** Pad-specific bootstrap data (JSON-serializable). `locale`, `messages`, `texts` are reserved. */
  bootstrap?: Record<string, unknown>;
  /** Extra vocabulary the page script reads via `t(key)`. */
  textKeys?: readonly VocabularyKey[];
  density?: 'comfortable' | 'compact';
  /** `data-role` on the app shell (e.g. the pad id). */
  role?: string;
}

/** The bootstrap object embedded as `#pad-bootstrap`. Reserved keys always win. */
export function buildPadBootstrap(
  options: Pick<PadPageOptions, 'locale' | 'bootstrap' | 'textKeys'>
): Record<string, unknown> {
  const keys = [...new Set<VocabularyKey>([...PAD_SHELL_TEXT_KEYS, ...(options.textKeys ?? [])])];
  return {
    ...(options.bootstrap ?? {}),
    locale: options.locale,
    messages: getUiMessageBundle(options.locale).messages,
    texts: padTexts(keys, options.locale),
  };
}

/** A complete pad HTML document on the shared kit. */
export function renderPadPage(options: PadPageOptions): string {
  const t = padT(options.locale);
  const density = options.density === 'compact' ? 'compact' : 'comfortable';
  const role = options.role ? ` data-role="${escapePadHtml(options.role)}"` : '';
  const script = options.scriptModule
    ? `<script type="module">${inlineScriptSource(options.scriptModule)}</script>`
    : '';
  return [
    '<!doctype html>',
    `<html lang="${escapePadHtml(options.locale)}">`,
    '<head>',
    '<meta charset="utf-8" />',
    '<meta name="viewport" content="width=device-width, initial-scale=1" />',
    '<meta name="color-scheme" content="light dark" />',
    `<title>${escapePadHtml(t('local_pads:page_title', { title: options.title }))}</title>`,
    `<script>${PAD_THEME_PREPAINT_SCRIPT}</script>`,
    `<link rel="stylesheet" href="${PAD_UI_ROUTES.tokens}" />`,
    `<link rel="stylesheet" href="${PAD_UI_ROUTES.stylesheet}" />`,
    options.headExtra ?? '',
    `<script type="application/json" id="pad-bootstrap">${toPadInlineJson(buildPadBootstrap(options))}</script>`,
    '</head>',
    '<body>',
    `<div class="kb-app-shell" data-density="${density}"${role}>`,
    '<main class="kb-app-shell__main">',
    `<noscript><div class="kb-callout" data-tone="warning"><div class="kb-callout__content"><p class="kb-callout__body">${escapePadHtml(t('local_pads:noscript_notice'))}</p></div></div></noscript>`,
    options.bodyHtml,
    '</main>',
    '</div>',
    script,
    '</body>',
    '</html>',
  ].join('\n');
}

