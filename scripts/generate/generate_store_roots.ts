/** Project catalog registrations into the existing foundation module; no runtime catalog reads. */
import { pathResolver } from '@agent/core/path-resolver';
import { compileSchema, readTextFile } from '@agent/core/foundation';
import { defineGenerator, isDirectScript } from '../lib/harness.js';
import { readSafeJsonFile } from '../lib/json-input.js';
import {
  projectStoreRoots,
  type StoreRootRegistries,
  type StoreRootSource,
} from '../lib/store-root-projection.js';

export const STORE_ROOTS_OUTPUT = 'libs/core/foundation/runtime-state-roots.ts';
export const STORE_ROOTS_BEGIN = '// GENERATED-STORE-ROOTS:BEGIN';
export const STORE_ROOTS_END = '// GENERATED-STORE-ROOTS:END';
const CATALOG = 'knowledge/product/governance/store-catalog.json';
const RETENTION = 'knowledge/product/governance/storage-retention-catalog.json';

export function buildStoreRootsBlock(roots: StoreRootRegistries): string {
  const declarations = [
    ['state', 'PARTITIONED_RUNTIME_STATE_ROOTS'],
    ['ledger', 'PARTITIONED_RUNTIME_LEDGER_ROOTS'],
    ['floor', 'STORAGE_FLOOR_ROOTS'],
  ] as const;
  return [
    STORE_ROOTS_BEGIN,
    '// Generated by scripts/generate/generate_store_roots.ts from store-catalog.json registrations.',
    ...declarations.flatMap(([family, name]) => [
      `export const ${name} = {`,
      ...Object.entries(roots[family]).map(([key, root]) => `  ${key}: '${root}',`),
      '} as const;',
      '',
    ]),
    STORE_ROOTS_END,
  ].join('\n');
}

/** Refuse missing, duplicated, reversed or embedded markers; preserve every outside byte. */
export function spliceStoreRootsBlock(source: string, roots: StoreRootRegistries): string {
  const markers = [STORE_ROOTS_BEGIN, STORE_ROOTS_END];
  const positions = markers.map((marker) => {
    const index = source.indexOf(marker);
    if (
      index < 0 ||
      source.indexOf(marker, index + marker.length) >= 0 ||
      (index > 0 && source[index - 1] !== '\n') ||
      !['\n', '\r', undefined].includes(source[index + marker.length])
    ) {
      throw new Error(`Expected exactly one standalone ${marker} marker`);
    }
    return index;
  });
  if (positions[0] >= positions[1]) throw new Error('Store root markers are reversed');
  return (
    source.slice(0, positions[0]) +
    buildStoreRootsBlock(roots) +
    source.slice(positions[1] + STORE_ROOTS_END.length)
  );
}

export function projectStoreRootSource(
  source: string,
  stores: readonly StoreRootSource[],
  retention: readonly { path: string }[],
  validateRoots?: (roots: StoreRootRegistries) => void
): string {
  const projected = projectStoreRoots(stores, retention);
  if (projected.violations.length) throw new Error(projected.violations.join('\n'));
  validateRoots?.(projected.roots);
  return spliceStoreRootsBlock(source, projected.roots);
}

/** Handwritten aliases outside the generated region require these canonical keys. */
export function assertCanonicalStoreRootAliases(roots: StoreRootRegistries): void {
  for (const key of ['tenant_ledger', 'tenant_approvals', 'tenant_audit_mirror', 'delegations']) {
    if (!Object.hasOwn(roots.ledger, key))
      throw new Error(`Missing mandatory store registration ledger:${key} for foundation alias`);
  }
}

interface StoreRootInputs {
  stores: readonly StoreRootSource[];
  retention: readonly { path: string }[];
}

/** Script-side construction seam for isolated harness tests; no CLI output override. */
export function createStoreRootsGenerator(
  output: string,
  loadInputs: () => StoreRootInputs,
  validateRoots?: (roots: StoreRootRegistries) => void
) {
  return defineGenerator({
    id: 'store-roots',
    outputs: [output],
    render() {
      const { stores, retention } = loadInputs();
      return [
        {
          path: output,
          content: projectStoreRootSource(readTextFile(output), stores, retention, validateRoots),
        },
      ];
    },
  });
}

export const main = createStoreRootsGenerator(
  pathResolver.rootResolve(STORE_ROOTS_OUTPUT),
  () => {
    const catalog = readSafeJsonFile<{ stores: StoreRootSource[] }>(
      pathResolver.rootResolve(CATALOG),
      'store catalog'
    );
    const retention = readSafeJsonFile<{ entries: { path: string }[] }>(
      pathResolver.rootResolve(RETENTION),
      'retention catalog'
    );
    for (const [value, schema] of [
      [catalog, 'knowledge/product/schemas/store-catalog.schema.json'],
      [retention, 'knowledge/product/schemas/storage-retention-catalog.schema.json'],
    ] as const) {
      const validate = compileSchema(pathResolver.rootResolve(schema));
      if (!validate(value)) throw new Error(`${schema}: ${JSON.stringify(validate.errors)}`);
    }
    return { stores: catalog.stores, retention: retention.entries };
  },
  assertCanonicalStoreRootAliases
);

if (
  isDirectScript(import.meta.url, 'generate_store_roots.ts') ||
  isDirectScript(import.meta.url, 'generate_store_roots.js')
)
  void main();
