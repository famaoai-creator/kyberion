/**
 * Generate the workspace package dependency graph
 * (`docs/developer/architecture/dependency-graph.mmd`).
 *
 * Nodes are the pnpm workspace packages; edges are their declared
 * `workspace:*` dependencies. The output is deterministic so `--check` can
 * fail CI when the committed graph drifts from the manifests. The root package
 * (scripts/) is drawn as `kyberion (root)`.
 */
import * as path from 'node:path';
import { readTextFile } from '@agent/core/foundation';
import { pathResolver } from '@agent/core/path-resolver';
import { safeExistsSync, safeReaddir, safeStat } from '@agent/core/secure-io';
import { defineGenerator, isDirectScript } from '../lib/harness.js';
import { readSafeJsonFile } from '../lib/json-input.js';

export const GRAPH_FILE = 'docs/developer/architecture/dependency-graph.mmd';
const OUTPUT_PATH = pathResolver.rootResolve(GRAPH_FILE);

interface WorkspacePackage {
  name: string;
  dir: string;
  group: string;
  workspaceDeps: string[];
}

interface PackageManifest {
  name?: string;
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
}

const GROUP_ORDER = ['root', 'kernel', 'core', 'shared', 'actuators', 'presence', 'satellites'];
const GROUP_LABEL: Record<string, string> = {
  root: 'Entry points',
  kernel: 'Kernel',
  core: 'Core',
  shared: 'Shared libraries',
  actuators: 'Actuators',
  presence: 'Presence surfaces',
  satellites: 'Satellites',
};

/** `packages:` globs from pnpm-workspace.yaml (`dir` or `dir/*` forms only). */
export function parseWorkspaceGlobs(yaml: string): string[] {
  const globs: string[] = [];
  let inPackages = false;
  for (const line of yaml.split(/\r?\n/u)) {
    if (/^packages:\s*$/u.test(line)) {
      inPackages = true;
      continue;
    }
    if (!inPackages) continue;
    const item = /^\s+-\s+['"]?([^'"#]+?)['"]?\s*$/u.exec(line);
    if (item) globs.push(item[1].trim());
    else if (/^\S/u.test(line)) break;
  }
  return globs;
}

/** Expand a workspace glob whose only wildcard is in the last segment (`libs/shared-*`). */
function expandGlob(glob: string): string[] {
  if (!glob.includes('*')) return [glob];
  const base = path.posix.dirname(glob);
  const pattern = new RegExp(
    `^${path.posix
      .basename(glob)
      .split('*')
      .map((part) => part.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&'))
      .join('[^/]*')}$`,
    'u'
  );
  const absolute = pathResolver.rootResolve(base);
  if (!safeExistsSync(absolute)) return [];
  return safeReaddir(absolute)
    .filter((entry) => pattern.test(entry))
    .sort()
    .map((entry) => path.posix.join(base, entry))
    .filter((dir) => safeStat(pathResolver.rootResolve(dir)).isDirectory());
}

function groupOf(dir: string): string {
  if (dir === '.') return 'root';
  if (dir === 'libs/kernel') return 'kernel';
  if (dir === 'libs/core') return 'core';
  if (dir.startsWith('libs/shared-')) return 'shared';
  if (dir.startsWith('libs/actuators/')) return 'actuators';
  if (dir.startsWith('presence/')) return 'presence';
  return 'satellites';
}

export function collectWorkspacePackages(): WorkspacePackage[] {
  const globs = parseWorkspaceGlobs(readTextFile(pathResolver.rootResolve('pnpm-workspace.yaml')));
  const dirs = ['.', ...globs.flatMap(expandGlob)];
  const manifests = dirs
    .map((dir) => ({ dir, file: pathResolver.rootResolve(path.posix.join(dir, 'package.json')) }))
    .filter(({ file }) => safeExistsSync(file))
    .map(({ dir, file }) => ({ dir, manifest: readSafeJsonFile<PackageManifest>(file, file) }))
    .filter(({ manifest }) => typeof manifest.name === 'string');
  const names = new Set(manifests.map(({ manifest }) => manifest.name as string));
  return manifests
    .map(({ dir, manifest }) => ({
      name: manifest.name as string,
      dir,
      group: groupOf(dir),
      workspaceDeps: Object.entries({ ...manifest.devDependencies, ...manifest.dependencies })
        .filter(([dep, version]) => names.has(dep) && version.startsWith('workspace:'))
        .map(([dep]) => dep)
        .sort(),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function nodeId(name: string): string {
  return name.replace(/^@/u, '').replace(/[^A-Za-z0-9]/gu, '_');
}

function nodeLabel(pkg: WorkspacePackage): string {
  return pkg.dir === '.' ? 'kyberion (root)' : pkg.name;
}

/** Render the Mermaid graph; layer groups become subgraphs, edges point at dependencies. */
export function renderDependencyGraph(packages: WorkspacePackage[]): string {
  const lines = [
    '%% Generated by scripts/generate/generate_package_dependency_graph.ts — do not edit by hand.',
    '%% Regenerate: node --import ./scripts/ts-loader.mjs scripts/generate/generate_package_dependency_graph.ts (CI: --check)',
    '%% Edges are declared workspace:* dependencies (A --> B means A depends on B).',
    'graph TD',
  ];
  for (const group of GROUP_ORDER) {
    const members = packages.filter((pkg) => pkg.group === group);
    if (members.length === 0) continue;
    lines.push(`  subgraph ${group} ["${GROUP_LABEL[group]}"]`);
    for (const pkg of members) lines.push(`    ${nodeId(pkg.name)}["${nodeLabel(pkg)}"]`);
    lines.push('  end');
  }
  for (const pkg of packages) {
    for (const dep of pkg.workspaceDeps) lines.push(`  ${nodeId(pkg.name)} --> ${nodeId(dep)}`);
  }
  return `${lines.join('\n')}\n`;
}

export const runGeneratePackageDependencyGraph = defineGenerator({
  id: 'package-dependency-graph',
  outputs: [OUTPUT_PATH],
  render() {
    return [{ path: OUTPUT_PATH, content: renderDependencyGraph(collectWorkspacePackages()) }];
  },
});

if (
  isDirectScript(import.meta.url, 'generate_package_dependency_graph.ts') ||
  isDirectScript(import.meta.url, 'generate_package_dependency_graph.js')
)
  void runGeneratePackageDependencyGraph();
